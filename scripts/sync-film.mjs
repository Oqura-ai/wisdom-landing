// Copies the film's drawing code out of the film page into lib/film/film.generated.js.
//
//   node scripts/sync-film.mjs [path/to/wisdom-team-final.html]
//
// The film page stays the source: every frame is a pure function of time, render(t). This script takes
// everything between its first 'use strict' and its player, unchanged, except the three web-font names,
// which point at the fonts the site self-hosts (passed in at runtime). It also exposes the few internals
// the landing's steady cut needs (lib/film/steady.ts). Run it again whenever the film changes.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.resolve(
  process.argv[2] ?? path.join(root, '..', 'assets', 'wisdom-team-final.html'),
);
const out = path.join(root, 'lib', 'film', 'film.generated.js');

const page = fs.readFileSync(src, 'utf8');
const start = page.indexOf("'use strict';");
const end = page.indexOf('// ---------- player');
if (start < 0 || end < start) throw new Error(`no film code in ${src}`);
let code = page.slice(start + "'use strict';".length, end);

const swap = (pattern, replacement, what) => {
  if (!pattern.test(code))
    throw new Error(`the film no longer declares ${what}; update scripts/sync-film.mjs`);
  code = code.replace(pattern, replacement);
};
swap(/^const HEAD=.*;$/m, 'const HEAD=FONTS.head;', 'HEAD');
swap(
  /^const MONO=.*?,SANS=.*?,SERIF=(.*);$/m,
  'const MONO=FONTS.mono,SANS=FONTS.sans,SERIF=$1;',
  'MONO, SANS and SERIF',
);
for (const name of [
  'render',
  'winState',
  'browState',
  'ghState',
  'termWindow',
  'browserWindow',
  'ghWindow2',
])
  if (!new RegExp(`function ${name}\\(`).test(code))
    throw new Error(`the film no longer has ${name}()`);

// the timeline constants, also exported on their own so pages can place chapters without building the film
const dur = /const FPS=\d+,DUR=([\d.]+);/.exec(code);
const warp = /const WARP=(\[\[.*?\]\]);/.exec(code);
if (!dur || !warp) throw new Error('the film no longer declares DUR and WARP as before');

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  `// GENERATED by scripts/sync-film.mjs from ${path.basename(src)}. Do not edit: change the film, then run the script.
/* eslint-disable */
// @ts-nocheck
export const FILM_DUR = ${Number(dur[1])};
export const FILM_WARP = ${JSON.stringify(JSON.parse(warp[1]))};

export function createFilm(FONTS) {
'use strict';
${code}
  return {
    render, DUR, WARP, keys, clamp, DEFS,
    resetIds() { uid = 0; },
    parts: { termWindow, installCards, recHud, askPanel, contPanel, teamPanel, particles, browserWindow, mouse, ghWindow2, ghMouse },
    windows: {
      get winState() { return winState; }, set winState(f) { winState = f; },
      get browState() { return browState; }, set browState(f) { browState = f; },
      get ghState() { return ghState; }, set ghState(f) { ghState = f; },
    },
  };
}
`,
);
console.log(
  `wrote ${path.relative(root, out)} from ${src} (${Math.round(code.length / 1024)} KB of film code)`,
);
